def _section_methods_e2(
    decisions: list[dict[str, Any]],
    props: dict[str, dict[str, Any]],
    roles: dict[str, str],
) -> list[str]:
    e2 = props["E2"]
    e2_id = str(e2["id"])
    classify = _explanation_for(
        decisions,
        rule_id="classification.derive_legal_effect",
        subject_id=e2_id,
    )
    compose = _explanation_for(
        decisions,
        rule_id="structured_list.compose_terminal_leaf",
        subject_id=e2_id,
    )
    exception = _explanation_for(
        decisions,
        rule_id="relationship.infer_exception_to",
        locator_substr="2-a-ii",
    )
    if exception is None:
        # fall back: match by source prop id in blob
        exception = _explanation_for(
            decisions,
            rule_id="relationship.infer_exception_to",
            locator_substr=e2_id,
        )
    group_target = _explanation_for(
        decisions,
        rule_id="relationship.prefer_group_target",
        locator_substr="article:49a:paragraph:1",
    )
    attach = _explanation_for(
        decisions,
        rule_id="effective_law.attach_applicable_exception",
        locator_substr=e2_id,
    )
    _ = roles
    rows = [
        (
            "paragraph 2 selection",
            "configuration / deterministic",
            "Required locator selected `article:49a:paragraph:2` for extraction.",
        ),
        (
            "descendant suppression",
            "deterministic",
            "Subparagraph (a) suppressed via `selection.prefer_required_ancestor`.",
        ),
        (
            "model-origin extraction candidate",
            "LLM proposal",
            "Frontier model proposed structured proposition row(s) for paragraph 2; "
            "retained E2 path `2-a-ii`.",
        ),
        (
            "deterministic structured composition",
            "deterministic",
            (
                str(compose.get("summary") or "").strip()
                if compose
                else "Terminal leaf composed on path 2-a-ii."
            ),
        ),
        (
            "deterministic derogation classification",
            "deterministic",
            (
                str(classify.get("summary") or "").strip()
                if classify
                else "Classified as derogation."
            ),
        ),
        (
            "deterministic exception relationship",
            "deterministic",
            (
                str(exception.get("summary") or "").strip()
                if exception
                else "Inferred exception_to targeting paragraph-1 group."
            ),
        ),
        (
            "deterministic group targeting",
            "deterministic",
            (
                str(group_target.get("summary") or "").strip()
                if group_target
                else "Preferred LegalRuleGroup target for paragraph 1."
            ),
        ),
        (
            "deterministic effective-law expansion",
            "deterministic",
            (
                str(attach.get("summary") or "").strip()
                if attach
                else "Expanded exception into applicable_exception / exception_target context."
            ),
        ),
    ]
    lines = [
        "## Methods table (E2)",
        "",
        "E2 is the worked example for method separation. The model did **not** "
        "decide all of these stages.",
        "",
        "| Decision | Method | Evidence |",
        "| --- | --- | --- |",
    ]
    for decision, method, evidence in rows:
        lines.append(f"| {decision} | {method} | {_short_text(evidence, 160)} |")
    lines.append("")
    return lines


