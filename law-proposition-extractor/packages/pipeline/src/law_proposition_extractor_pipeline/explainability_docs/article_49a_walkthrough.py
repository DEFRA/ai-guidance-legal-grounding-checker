        f"- **Manifestation type (authority-supplied):** `{manifestation_type}`",
        f"- **Manifestation basis:** `{manifestation_basis}`",
        "",
        "### Provenance decisions (Why panel)",
        "",
        "Why the snapshot is labelled revised:",
        "",
        f"- rule `provenance.classify_manifestation` → "
        f"`{(classify or {}).get('outcome') or 'classified_as_revised'}` "
        f"with winning basis `{manifestation_basis}` "
        "(source metadata such as DocumentStatus=revised).",
        "",
        "Why no legal as-of date is claimed:",
        "",
        f"- rule `provenance.preserve_as_of_unknown` → "
        f"`{(as_of or {}).get('outcome') or 'legal_as_of_not_established'}`. "
        "Retrieval time is operational; source revision date is authority "
        "metadata; neither was treated as legal as-of.",
        "",
        "Why the Article-level effect reaches paragraph statements:",
        "",
        f"- rule `source_effect.inherit_from_structural_ancestor` "
        f"({len(inherit)} recorded inheritance decision"
        f"{'' if len(inherit) == 1 else 's'}). "
        "The annotation is attached to Article 49a as a whole and is shown "
        "for propositions extracted from paragraphs within Article 49a.",
        "",
        "Why Article 1 effects do not:",
        "",
        f"- rule `source_effect.exclude_unrelated_fragment` "
        f"({len(exclude)} recorded exclusion decision"
        f"{'' if len(exclude) == 1 else 's'}). "
        "Article 1 is not a structural ancestor of Article 49a.",
        "",
        "What independent-consumption status means:",
        "",
        f"- rule `source_effect.assess_independent_consumption` "
        f"(example outcome `"
        f"{(consumption or {}).get('outcome') or 'not_matched'}`). "
        "Run-scoped identity match only — not proof that Law Proposition Extractor applied or "
        "verified the amendment.",
        "",
        "The fixture records a **revised** manifestation from legislation.gov.uk "
        "metadata. That does **not** prove Law Proposition Extractor independently applied every "
        "amendment or verified outstanding effects. Retrieval timestamps and "
