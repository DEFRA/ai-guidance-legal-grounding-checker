def _section_extraction_frontier(decisions: list[dict[str, Any]]) -> list[str]:
    child = _explanation_for(
        decisions,
        rule_id="selection.prefer_required_children",
        locator_substr="article:49a",
    )
    ancestor = _explanation_for(
        decisions,
        rule_id="selection.prefer_required_ancestor",
        locator_substr="subparagraph:a",
    )
    child_summary = _short_text(
        str(child.get("summary") or "").strip()
        if child
        else "Parent suppressed because selected children cover its operative text.",
        200,
    )
    ancestor_summary = _short_text(
        str(ancestor.get("summary") or "").strip()
        if ancestor
        else "Descendant suppressed because a required ancestor covers its legal text.",
        200,
    )
    return [
        "## Extraction frontier",
        "",
        "**Selected for extraction:**",
        "",
        "- `article:49a:paragraph:1` — required locator",
        "- `article:49a:paragraph:2` — required locator",
        "- `article:49a:paragraph:3` — required locator",
        "",
        "**Suppressed (not separately extracted):**",
        "",
        f"- `article:49a` (Article 49a parent) — rule "
        f"`selection.prefer_required_children`: {child_summary}",
        f"- `article:49a:paragraph:2:subparagraph:a` (paragraph 2(a) descendant) — "
        f"rule `selection.prefer_required_ancestor`: {ancestor_summary}",
        "",
    ]


def _section_propositions(props: dict[str, dict[str, Any]], roles: dict[str, str]) -> list[str]:
    lines = [
        "## Six propositions",
        "",
        "| Role | Source locator | Structured-list path | Legal effect | Short operative description |",
        "| --- | --- | --- | --- | --- |",
    ]
    for role in _ROLE_ORDER:
        prop = props[role]
        path = structured_list_path(prop) or "—"
        lines.append(
            "| {role} ({desc}) | `{loc}` | `{path}` | `{effect}` | {text} |".format(
                role=role,
                desc=_ROLE_DESCRIPTIONS[role],
                loc=prop.get("fragment_locator") or "",
                path=path,
                effect=prop.get("legal_effect_type") or "",
                text=_short_text(str(prop.get("proposition_text") or "")),
            )
        )
    lines.append("")
    lines.append(
        "Opaque proposition IDs are intentionally omitted from this table. "
        "Roles are stable; IDs may change across regenerations of the fixture."
    )
    lines.append("")
    assert len(props) == 6
    _ = roles
    return lines


