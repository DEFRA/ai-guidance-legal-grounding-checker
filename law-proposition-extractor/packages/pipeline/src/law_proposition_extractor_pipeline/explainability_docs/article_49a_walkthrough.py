_ROLE_ORDER = ("P1", "P2", "E1", "E2", "E3", "P3")
_ROLE_DESCRIPTIONS = {
    "P1": "separate-identification obligation",
    "P2": "no-mixing prohibition",
    "E1": "path 2-a-i exception",
    "E2": "path 2-a-ii exception",
    "E3": "path 2-b exception",
    "P3": "paragraph-3 monitoring obligation",
}


def render_article_49a_walkthrough_body() -> str:
    """Render the GENERATED factual walkthrough body (no outer markers)."""
    fixture = fixture_dir()
    bundle = load_serialized_bundle(fixture)
    roles = resolve_roles(bundle)
    provenance = load_provenance(fixture)
    content_hash = fixture_content_hash(fixture)

    missing = [r for r in _ROLE_ORDER if r not in roles]
    if missing:
        raise RuntimeError(f"Missing semantic roles: {missing!r}")

    props = {role: prop_by_id(bundle, roles[role]) for role in _ROLE_ORDER}
    decisions = _decisions(bundle)
    groups = _groups(bundle)
    relationships = _relationships(bundle)
    statements = _statements(bundle)
    decision_schema = str((bundle.get("decision_explanations") or {}).get("schema_version") or "1")

    lines: list[str] = []
    lines.append(
        "This walkthrough is generated from the offline Article 49a acceptance "
        "fixture and its serialized decision artifacts. Opaque live IDs are "
        "resolved through stable semantic roles (P1-P3, E1-E3)."
    )
    lines.append("")
    lines.append(f"_Generated by `{GENERATION_COMMAND}`._")
    lines.append("")

    lines.extend(_section_source_and_provenance(bundle, provenance))
    lines.extend(_section_structural_hierarchy())
    lines.extend(_section_extraction_frontier(decisions))
    lines.extend(_section_propositions(props, roles))
    lines.extend(_section_structured_lists(props, decisions, roles))
    lines.extend(_section_classification(props, decisions, roles))
    lines.extend(_section_groups(groups, roles))
    lines.extend(_section_relationships(relationships, roles))
    lines.extend(_section_effective_law(statements, props, roles))
    lines.extend(_section_article_14(statements, props, roles))
    lines.extend(_section_source_effects(bundle))
    lines.extend(_section_workbench())
    lines.extend(_section_methods_e2(decisions, props, roles))
    lines.extend(_section_not_proved())
    lines.extend(
        _section_provenance_footer(
            provenance=provenance,
            content_hash=content_hash,
            decision_schema=decision_schema,
        )
    )
    return "\n".join(lines).rstrip() + "\n"


def _decisions(bundle: dict[str, Any]) -> list[dict[str, Any]]:
    raw = bundle.get("decision_explanations")
    if isinstance(raw, dict):
        rows = raw.get("decisions") or []
        return [r for r in rows if isinstance(r, dict)]
    if isinstance(raw, list):
        return [r for r in raw if isinstance(r, dict)]
    return []


def _groups(bundle: dict[str, Any]) -> list[dict[str, Any]]:
    raw = bundle.get("legal_rule_groups")
    if isinstance(raw, dict):
        return [g for g in (raw.get("groups") or []) if isinstance(g, dict)]
    if isinstance(raw, list):
        return [g for g in raw if isinstance(g, dict)]
    return []


def _relationships(bundle: dict[str, Any]) -> list[dict[str, Any]]:
    raw = bundle.get("legal_rule_relationships")
    if isinstance(raw, dict):
        return [r for r in (raw.get("relationships") or []) if isinstance(r, dict)]
    if isinstance(raw, list):
        return [r for r in raw if isinstance(r, dict)]
    return []


def _statements(bundle: dict[str, Any]) -> list[dict[str, Any]]:
    raw = bundle.get("effective_law_statements")
    if isinstance(raw, dict):
        return [s for s in (raw.get("statements") or []) if isinstance(s, dict)]
    if isinstance(raw, list):
        return [s for s in raw if isinstance(s, dict)]
    return []


def _short_text(text: str, limit: int = 110) -> str:
    cleaned = " ".join(str(text or "").split())
    # Keep walkthrough prose free of opaque live IDs.
    cleaned = re.sub(r"\bprop:[0-9a-f]+\b", "proposition", cleaned)
    cleaned = re.sub(r"\brulegrp:[0-9a-f]+\b", "legal-rule-group", cleaned)
    cleaned = re.sub(r"\blegalrel:[0-9a-f]+\b", "legal-relationship", cleaned)
    cleaned = re.sub(r"\blawstmt:[0-9a-f]+\b", "effective-law-statement", cleaned)
    cleaned = re.sub(r"\bdecision:[0-9a-f]+\b", "decision", cleaned)
    if len(cleaned) <= limit:
        return cleaned
    return cleaned[: limit - 1].rstrip() + "…"


def _role_for_prop(roles: dict[str, str], prop_id: str) -> str | None:
    for role, pid in roles.items():
        if pid == prop_id:
            return role
    return None


def _explanation_for(
    decisions: list[dict[str, Any]],
    *,
    rule_id: str,
    locator_substr: str | None = None,
    subject_id: str | None = None,
) -> dict[str, Any] | None:
    for row in decisions:
        if str(row.get("rule_id") or "") != rule_id:
            continue
        if subject_id is not None and str(row.get("subject_id") or "") != subject_id:
            continue
        if locator_substr is not None:
            blob = json_blob(row)
            if locator_substr not in blob:
                continue
        return row
    return None


def json_blob(row: dict[str, Any]) -> str:
    parts: list[str] = [str(row.get("summary") or "")]
    for key in ("evidence", "inputs", "alternatives", "suppressed_items"):
        for item in row.get(key) or []:
            if isinstance(item, dict):
                parts.append(str(item.get("value") or ""))
                parts.append(str(item.get("label") or ""))
    return " ".join(parts)


