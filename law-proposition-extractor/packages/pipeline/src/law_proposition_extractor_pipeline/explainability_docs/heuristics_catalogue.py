"""Generate the heuristic catalogue Markdown section from the registry."""

from __future__ import annotations

from collections import Counter

from law_proposition_extractor_domain import DecisionStage, HeuristicMethod

from law_proposition_extractor_pipeline.heuristics import REGISTRY_VERSION, list_heuristics
from law_proposition_extractor_pipeline.heuristics.explainability_coverage import (
    EMISSION_SITES,
    emits_decision_explanation,
    rules_emitting_explanations,
    rules_not_yet_emitting_explanations,
)

from .paths import GENERATION_COMMAND

_STAGE_SECTIONS: tuple[tuple[str, tuple[DecisionStage, ...] | None], ...] = (
    ("Provenance", (DecisionStage.PROVENANCE,)),
    ("Selection", (DecisionStage.SELECTION,)),
    ("Extraction and structured lists", (DecisionStage.EXTRACTION,)),
    ("Classification", (DecisionStage.CLASSIFICATION,)),
    ("Grouping", (DecisionStage.GROUPING,)),
    ("Relationships", (DecisionStage.RELATIONSHIP,)),
    ("Effective law", (DecisionStage.EFFECTIVE_LAW,)),
    ("Source effects", (DecisionStage.SOURCE_EFFECT,)),
    ("Other registered stages", None),
)

_METHOD_LABELS: dict[HeuristicMethod, str] = {
    HeuristicMethod.DETERMINISTIC: "Deterministic rule",
    HeuristicMethod.CONFIGURATION: "Configuration rule",
    HeuristicMethod.LLM: "LLM-assisted rule",
    HeuristicMethod.HYBRID: "Hybrid rule",
    HeuristicMethod.HUMAN: "Human rule",
}


def render_heuristic_catalogue() -> str:
    """Render coverage summary + full catalogue for the GENERATED section."""
    heuristics = list(list_heuristics())
    emitting = set(rules_emitting_explanations())
    not_emitting = list(rules_not_yet_emitting_explanations())

    by_method = Counter(h.method.value for h in heuristics)
    claimed_stages = {
        DecisionStage.PROVENANCE,
        DecisionStage.SELECTION,
        DecisionStage.EXTRACTION,
        DecisionStage.CLASSIFICATION,
        DecisionStage.GROUPING,
        DecisionStage.RELATIONSHIP,
        DecisionStage.EFFECTIVE_LAW,
        DecisionStage.SOURCE_EFFECT,
    }
    remaining = [h for h in heuristics if h.stage not in claimed_stages]

    def _count_for(title: str, stages: tuple[DecisionStage, ...] | None) -> int:
        if title == "Other registered stages":
            return len(remaining)
        assert stages is not None
        return sum(1 for h in heuristics if h.stage in stages)

    lines: list[str] = []
    lines.append(f"_Registry version: `{REGISTRY_VERSION}`._")
    lines.append("")
    lines.append(f"_Generated by `{GENERATION_COMMAND}`._")
    lines.append("")
    lines.append("## Coverage summary")
    lines.append("")
    lines.append(f"- **Registry rule count:** {len(heuristics)}")
    lines.append("- **Rules by stage:**")
    for stage_name, stages in _STAGE_SECTIONS:
        lines.append(f"  - {stage_name}: {_count_for(stage_name, stages)}")
    lines.append("- **Rules by method:**")
    for method in sorted(by_method):
        lines.append(f"  - `{method}`: {by_method[method]}")
    lines.append(f"- **Rules currently emitting DecisionExplanations:** {len(emitting)}")
    lines.append(f"- **Registered rules not yet emitting decisions:** {len(not_emitting)}")
    if not_emitting:
        for rule_id in not_emitting:
            lines.append(f"  - `{rule_id}`")
    else:
        lines.append("  - _(none — every registered rule currently has a declared emission site)_")
    lines.append("")
    lines.append(
        "Emission coverage is declared in "
        "`law_proposition_extractor_pipeline.heuristics.explainability_coverage`, not inferred "
        "from registry membership alone."
    )
    lines.append("")

    for title, stages in _STAGE_SECTIONS:
        lines.append(f"## {title}")
        lines.append("")
        if title == "Other registered stages":
            if not remaining:
                lines.append("_No additional registered stages beyond the groups above._")
                lines.append("")
                continue
            group = remaining
        else:
            assert stages is not None
            group = [h for h in heuristics if h.stage in stages]
            if not group:
                lines.append("_No rules registered for this stage._")
                lines.append("")
                continue
        for heuristic in group:
            lines.extend(_render_rule(heuristic))
            lines.append("")

    rendered_ids: list[str] = []
    for line in lines:
        if line.startswith("## `") and "` — version" in line:
            rendered_ids.append(line[4:].split("`", 1)[0])
    if len(rendered_ids) != len(set(rendered_ids)):
        raise RuntimeError("Duplicate heuristic sections in generated catalogue.")
    expected = [h.rule_id for h in heuristics]
    if sorted(rendered_ids) != sorted(expected):
        missing = sorted(set(expected) - set(rendered_ids))
        extra = sorted(set(rendered_ids) - set(expected))
        raise RuntimeError(f"Catalogue/rule mismatch. Missing={missing!r} Extra={extra!r}.")

    return "\n".join(lines).rstrip() + "\n"


def _render_rule(heuristic) -> list[str]:
    method_label = _METHOD_LABELS.get(heuristic.method, str(heuristic.method.value))
    emits = emits_decision_explanation(heuristic.rule_id)
    emission = EMISSION_SITES.get(heuristic.rule_id)
    lines = [
        f"## `{heuristic.rule_id}` — version {heuristic.version}",
        "",
        f"**Method:** {method_label}",
        "",
        f"**What it does:** {heuristic.plain_english_summary}",
        "",
        f"**Runs after / precedence:** {heuristic.precedence_summary}",
        "",
        f"**Trigger:** {heuristic.trigger_summary}",
        "",
        f"**Outputs:** {', '.join(f'`{k}`' for k in heuristic.output_kinds) or '_(none)_'}",
        "",
        f"**Failure behaviour:** {heuristic.failure_mode}",
        "",
        (
            "**Diagnostics:** "
            + (
                ", ".join(f"`{c}`" for c in heuristic.diagnostic_codes)
                if heuristic.diagnostic_codes
                else "_(none declared)_"
            )
        ),
        "",
        (
            "**Source modules/symbols:** "
            + (
                ", ".join(f"`{c}`" for c in heuristic.code_references)
                if heuristic.code_references
                else "_(none)_"
            )
        ),
        "",
        (
            "**Tests:** "
            + (
                ", ".join(f"`{t}`" for t in heuristic.test_references)
                if heuristic.test_references
                else "_(none)_"
            )
        ),
        "",
        f"**Example:** {heuristic.example_summary}",
        "",
        (
            "**DecisionExplanation emission:** "
            + (f"yes — `{emission}`" if emits and emission else "not yet declared")
        ),
    ]
    return lines
